$ErrorActionPreference = "Stop"

$scriptDirectory = Split-Path -Parent $MyInvocation.MyCommand.Path
$projectRoot = (Resolve-Path (Join-Path $scriptDirectory "..")).Path
$backendDirectory = Join-Path $projectRoot "backend"
$frontendDirectory = Join-Path $projectRoot "frontend"
$pythonPath = Join-Path $backendDirectory ".venv\Scripts\python.exe"
$localEnvPath = Join-Path $backendDirectory ".env.local"
$frontendDevEnvPath = Join-Path $frontendDirectory ".env.development.local"
$databaseUrl = "postgresql://smartgallery:smartgallery_local_only@127.0.0.1:5432/smartgallery"
$redisUrl = "redis://127.0.0.1:6379/0"

function Set-EnvValue {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][string]$Key,
        [Parameter(Mandatory = $true)][string]$Value
    )

    $lines = [Collections.Generic.List[string]]::new()
    if (Test-Path -LiteralPath $Path) {
        foreach ($line in Get-Content -LiteralPath $Path) {
            $lines.Add($line)
        }
    }

    $prefix = "$Key="
    $updated = $false
    for ($index = 0; $index -lt $lines.Count; $index++) {
        if ($lines[$index].StartsWith($prefix, [StringComparison]::Ordinal)) {
            $lines[$index] = "$prefix$Value"
            $updated = $true
        }
    }
    if (-not $updated) {
        $lines.Add("$prefix$Value")
    }

    [IO.File]::WriteAllLines($Path, $lines, [Text.UTF8Encoding]::new($false))
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    throw "Docker Desktop is required. Install and start Docker, then run this script again."
}
if (-not (Test-Path -LiteralPath $pythonPath)) {
    throw "Backend virtual environment not found. Create backend\.venv and install requirements first."
}

Push-Location $projectRoot
try {
    docker compose up -d database redis
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose could not start the local services."
    }

    $ready = $false
    for ($attempt = 1; $attempt -le 30; $attempt++) {
        docker compose exec -T database pg_isready -U smartgallery -d smartgallery 2>$null | Out-Null
        if ($LASTEXITCODE -eq 0) {
            $ready = $true
            break
        }
        Start-Sleep -Seconds 2
    }
    if (-not $ready) {
        throw "PostgreSQL did not become healthy within 60 seconds. Run 'docker compose logs database'."
    }

    $localAuthToken = $null
    if (Test-Path -LiteralPath $localEnvPath) {
        $existingDatabaseLine = Get-Content -LiteralPath $localEnvPath |
            Where-Object { $_ -match '^DATABASE_URL=' } |
            Select-Object -First 1
        if ($existingDatabaseLine -and $existingDatabaseLine -ne "DATABASE_URL=$databaseUrl") {
            throw "backend\.env.local already targets another database; it was not overwritten."
        }
        $existingTokenLine = Get-Content -LiteralPath $localEnvPath |
            Where-Object { $_ -match '^LOCAL_DEV_AUTH_TOKEN=' } |
            Select-Object -First 1
        if ($existingTokenLine) {
            $localAuthToken = $existingTokenLine.Substring("LOCAL_DEV_AUTH_TOKEN=".Length)
        }
    } else {
        $secretKey = [guid]::NewGuid().ToString("N") + [guid]::NewGuid().ToString("N")
        $localSettings = @(
            "# Generated by scripts/setup-local.ps1. Local development only."
            "DEBUG=true"
            "EXPOSE_API_DOCS=true"
            "SECRET_KEY=$secretKey"
            "DATABASE_URL=$databaseUrl"
            "REDIS_URL=$redisUrl"
            "CELERY_BROKER_URL=$redisUrl"
            "CELERY_RESULT_BACKEND=$redisUrl"
        )
        [IO.File]::WriteAllLines($localEnvPath, $localSettings, [Text.UTF8Encoding]::new($false))
        Write-Output "Created ignored backend\.env.local with local-only settings."
    }

    if (-not $localAuthToken -or $localAuthToken.Length -lt 32) {
        $localAuthToken = [guid]::NewGuid().ToString("N") + [guid]::NewGuid().ToString("N")
    }
    Set-EnvValue -Path $localEnvPath -Key "APP_ENVIRONMENT" -Value "development"
    Set-EnvValue -Path $localEnvPath -Key "LOCAL_DEV_AUTH" -Value "true"
    Set-EnvValue -Path $localEnvPath -Key "LOCAL_DEV_AUTH_TOKEN" -Value $localAuthToken
    Set-EnvValue -Path $localEnvPath -Key "LOCAL_DEV_USER_EMAIL" -Value "developer@localhost"

    Set-EnvValue -Path $frontendDevEnvPath -Key "NEXT_PUBLIC_API_URL" -Value "http://127.0.0.1:8000/api"
    Set-EnvValue -Path $frontendDevEnvPath -Key "NEXT_PUBLIC_LOCAL_DEV_AUTH" -Value "true"
    Set-EnvValue -Path $frontendDevEnvPath -Key "NEXT_PUBLIC_LOCAL_DEV_AUTH_TOKEN" -Value $localAuthToken
    Write-Output "Configured ignored local development authentication for backend and frontend."

    $env:DATABASE_URL = $databaseUrl
    $env:SECRET_KEY = [guid]::NewGuid().ToString("N") + [guid]::NewGuid().ToString("N")
    Push-Location $backendDirectory
    try {
        & $pythonPath -m alembic upgrade head
        if ($LASTEXITCODE -ne 0) {
            throw "Database migrations failed."
        }
    } finally {
        Pop-Location
    }

    Write-Output "Local PostgreSQL/pgvector and Redis are ready."
    Write-Output "Start the API: cd backend; .venv\Scripts\python -m uvicorn app.main:app --reload --port 8000"
    Write-Output "Health check: http://localhost:8000/api/health"
    Write-Output "Stop services without deleting data: docker compose down"
} finally {
    Pop-Location
}
